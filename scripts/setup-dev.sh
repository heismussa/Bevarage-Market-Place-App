#!/usr/bin/env bash
# Local development setup for macOS and Linux: creates .env with random local secrets
# (if it does not exist), starts Docker, applies migrations and loads demo data.
# Safe to run again. Usage: bash scripts/setup-dev.sh
set -euo pipefail
cd "$(dirname "$0")/.."

secret() { head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }

if ! docker info >/dev/null 2>&1; then
  echo "Docker is not running. Start Docker Desktop, then run this script again." >&2
  exit 1
fi

if [ -f .env ]; then
  echo ".env already exists; keeping your values."
else
  db_password=$(secret 16)
  {
    echo "# Generated by scripts/setup-dev.sh for LOCAL development only. ALLOWED_HOSTS=* lets phones on your Wi-Fi reach the API; never use these values on a server."
    awk -v secret_key="$(secret 40)" -v db="$db_password" -v webhook="$(secret 32)" \
        -v admin="Admin-$(secret 6)" -v customer="Customer-$(secret 6)" -v owner="Owner-$(secret 6)" '
      /^SECRET_KEY=/ { print "SECRET_KEY=" secret_key; next }
      /^ALLOWED_HOSTS=/ { print "ALLOWED_HOSTS=*"; next }
      /^CORS_ALLOWED_ORIGINS=/ { print "CORS_ALLOWED_ORIGINS=http://localhost:5173,http://localhost:8081,http://localhost:3000"; next }
      /^POSTGRES_PASSWORD=/ { print "POSTGRES_PASSWORD=" db; next }
      /^DATABASE_URL=/ { print "DATABASE_URL=postgres://beverage:" db "@db:5432/beverage"; next }
      /^MOCK_PAYMENT_WEBHOOK_SECRET=/ { print "MOCK_PAYMENT_WEBHOOK_SECRET=" webhook; next }
      /^DEMO_ADMIN_PASSWORD=/ { print "DEMO_ADMIN_PASSWORD=" admin; next }
      /^DEMO_CUSTOMER_PASSWORD=/ { print "DEMO_CUSTOMER_PASSWORD=" customer; next }
      /^DEMO_STORE_OWNER_PASSWORD=/ { print "DEMO_STORE_OWNER_PASSWORD=" owner; next }
      { print }
    ' .env.example
  } > .env
  echo "Created .env with random local secrets."
fi

docker compose up --build -d

echo "Waiting for the API..."
for _ in $(seq 1 90); do
  if curl -fsS http://localhost:8000/api/v1/health/ >/dev/null 2>&1; then ready=1; break; fi
  sleep 2
done
if [ -z "${ready:-}" ]; then
  echo "The API did not start. Run: docker compose logs backend" >&2
  exit 1
fi

docker compose exec -T backend python manage.py migrate --noinput
docker compose exec -T backend python manage.py seed_demo

value() { grep -E "^$1=" .env | head -n1 | cut -d= -f2-; }
ip=$( (ipconfig getifaddr en0 || hostname -I | awk '{print $1}') 2>/dev/null || true)

echo
echo "Backend is ready."
echo "  API docs:        http://localhost:8000/api/docs/"
echo "  Django admin:    http://localhost:8000/admin/"
[ -n "$ip" ] && echo "  From your phone: http://$ip:8000/api/v1/  (same Wi-Fi)"
echo
echo "Demo logins (your own local passwords, stored in .env):"
echo "  Customer        +255712345002  $(value DEMO_CUSTOMER_PASSWORD)"
echo "  ABC Drinks      +255712345003  $(value DEMO_STORE_OWNER_PASSWORD)"
echo "  Fresh Beverages +255712345004  $(value DEMO_STORE_OWNER_PASSWORD)"
echo "  Admin           +255712345001  $(value DEMO_ADMIN_PASSWORD)"
