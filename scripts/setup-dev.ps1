# Local development setup for Windows: creates .env with random local secrets (if it
# does not exist), starts Docker, applies migrations and loads demo data.
# Safe to run again. Usage: powershell -ExecutionPolicy Bypass -File scripts\setup-dev.ps1

$ErrorActionPreference = "Stop"
Set-Location (Split-Path $PSScriptRoot -Parent)

function New-Secret([int]$bytes) {
    $buffer = New-Object byte[] $bytes
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buffer)
    ($buffer | ForEach-Object { $_.ToString("x2") }) -join ""
}

function Invoke-Native([scriptblock]$command, [string]$failure) {
    & $command
    if ($LASTEXITCODE -ne 0) { throw $failure }
}

docker info *> $null
if ($LASTEXITCODE -ne 0) { throw "Docker is not running. Start Docker Desktop, wait until it says Running, then run this script again." }

if (Test-Path .env) {
    Write-Host ".env already exists; keeping your values." -ForegroundColor Yellow
} else {
    $dbPassword = New-Secret 16
    $values = @{
        SECRET_KEY                  = New-Secret 40
        ALLOWED_HOSTS               = "*"
        CORS_ALLOWED_ORIGINS        = "http://localhost:5173,http://localhost:8081,http://localhost:3000"
        POSTGRES_PASSWORD           = $dbPassword
        DATABASE_URL                = "postgres://beverage:$dbPassword@db:5432/beverage"
        MOCK_PAYMENT_WEBHOOK_SECRET = New-Secret 32
        DEMO_ADMIN_PASSWORD         = "Admin-" + (New-Secret 6)
        DEMO_CUSTOMER_PASSWORD      = "Customer-" + (New-Secret 6)
        DEMO_STORE_OWNER_PASSWORD   = "Owner-" + (New-Secret 6)
    }
    $lines = Get-Content .env.example | ForEach-Object {
        if ($_ -match '^([A-Z_]+)=' -and $values.ContainsKey($Matches[1])) {
            "$($Matches[1])=$($values[$Matches[1]])"
        } else {
            $_
        }
    }
    $header = "# Generated by scripts/setup-dev.ps1 for LOCAL development only. ALLOWED_HOSTS=* lets phones on your Wi-Fi reach the API; never use these values on a server."
    Set-Content -Path .env -Value (@($header) + $lines) -Encoding ascii
    Write-Host "Created .env with random local secrets." -ForegroundColor Green
}

Invoke-Native { docker compose up --build -d } "docker compose up failed. Read the error above."

Write-Host "Waiting for the API..."
$ready = $false
for ($i = 0; $i -lt 90; $i++) {
    try {
        Invoke-RestMethod -Uri "http://localhost:8000/api/v1/health/" -TimeoutSec 2 | Out-Null
        $ready = $true
        break
    } catch {
        Start-Sleep -Seconds 2
    }
}
if (-not $ready) { throw "The API did not start. Run: docker compose logs backend" }

Invoke-Native { docker compose exec -T backend python manage.py migrate --noinput } "migrate failed."
Invoke-Native { docker compose exec -T backend python manage.py seed_demo } "seed_demo failed."

$settings = @{}
Get-Content .env | Where-Object { $_ -match '^([A-Z_]+)=(.*)$' } | ForEach-Object { $settings[$Matches[1]] = $Matches[2] }
$ip = (Get-NetIPConfiguration -ErrorAction SilentlyContinue |
    Where-Object { $_.IPv4DefaultGateway -and $_.NetAdapter.Status -eq "Up" -and $_.InterfaceAlias -notmatch "vEthernet|WSL|VPN|Radmin|VirtualBox|VMware|Tailscale|ZeroTier" } |
    Select-Object -First 1).IPv4Address.IPAddress

Write-Host ""
Write-Host "Backend is ready." -ForegroundColor Green
Write-Host "  API docs:        http://localhost:8000/api/docs/"
Write-Host "  Django admin:    http://localhost:8000/admin/"
if ($ip) { Write-Host "  From your phone: http://${ip}:8000/api/v1/  (same Wi-Fi)" }
Write-Host ""
Write-Host "Demo logins (your own local passwords, stored in .env):"
Write-Host "  Customer        +255712345002  $($settings['DEMO_CUSTOMER_PASSWORD'])"
Write-Host "  ABC Drinks      +255712345003  $($settings['DEMO_STORE_OWNER_PASSWORD'])"
Write-Host "  Fresh Beverages +255712345004  $($settings['DEMO_STORE_OWNER_PASSWORD'])"
Write-Host "  Admin           +255712345001  $($settings['DEMO_ADMIN_PASSWORD'])"
